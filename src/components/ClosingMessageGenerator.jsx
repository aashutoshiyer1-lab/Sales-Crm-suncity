// Grammar & Cleaning Helper Function
// Helper to detect if a note is computer-generated boilerplate
export const isAutoGeneratedNote = (text) => {
  if (!text) return false;
  const t = String(text).trim();
  if (/^given\s+\d+%/i.test(t)) return true;
  if (/^given\s+.*discount/i.test(t)) return true;
  if (/^given\s+complementary/i.test(t)) return true;
  if (/^complimentary\s+game/i.test(t)) return true;
  if (/^prepaid\s+booking/i.test(t)) return true;
  if (/^website\s+booking/i.test(t)) return true;
  if (/^activity\s+kids/i.test(t)) return true;
  if (/^today\s+we\s+had/i.test(t)) return true;
  return false;
};

export const formatCustomNoteGrammar = (raw) => {
  if (!raw) return '';
  let cleaned = String(raw).trim();
  // Strip prefixes like "Note:", "note -", "Custom note:", etc.
  cleaned = cleaned.replace(/^(note\s*:\s*|note\s*-\s*|custom\s*note\s*:\s*|custom\s*note\s*-\s*|custom\s*reason\s*:\s*|note\s+)/i, '').trim();
  if (!cleaned) return '';
  // Capitalize first letter
  cleaned = cleaned.charAt(0).toUpperCase() + cleaned.slice(1);
  // Ensure closing punctuation
  if (!/[.!?]$/.test(cleaned)) {
    cleaned += '.';
  }
  return cleaned;
};

// Helper to aggregate payments for any set of bookings
export const aggregatePayments = (bookingsList = []) => {
  const totals = {
    Cash: 0,
    Card: 0,
    'UPI-New Pay': 0,
    'Prepaid by District': 0,
    'Razorpay (Website Bookings)': 0,
    'Activity Kids': 0
  };
  bookingsList.forEach(b => {
    if (b.payments) {
      Object.keys(totals).forEach(method => {
        let val = Number(b.payments[method]) || 0;
        if (!val && method === 'Razorpay (Website Bookings)') {
          val = Number(b.payments['Razorpay( website bookings)']) || Number(b.payments['Razorpay']) || 0;
        }
        if (!val && method === 'Activity Kids') {
          val = Number(b.payments['Activity kids']) || 0;
        }
        totals[method] += val;
      });
    }
  });
  return totals;
};

